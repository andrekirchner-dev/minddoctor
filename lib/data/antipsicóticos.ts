export function cpzEquivalente(droga: Antipsicótico, dose: number): number {
  return (dose / droga.cpz_eq_mg) * 100;
}

export function doseEquivalente(
  cpzTotal: number,
  drogaAlvo: Antipsicótico
): number {
  return (cpzTotal / 100) * drogaAlvo.cpz_eq_mg;
}
